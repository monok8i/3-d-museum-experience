function TypewriterParagraph({ text, delay }: { text: string; delay: number }) {
  const [displayedText, setDisplayedText] = useState("")
  const [started, setStarted] = useState(false)

  useEffect(() => {
    const timer = setTimeout(() => setStarted(true), delay * 1000)
    return () => clearTimeout(timer)
  }, [delay])

  useEffect(() => {
    if (!started) return

    let i = 0
    const interval = setInterval(() => {
      setDisplayedText(text.slice(0, i + 1))
      i++
      if (i >= text.length) clearInterval(interval)
    }, 25) // Speed of typing - 25ms per char

    return () => clearInterval(interval)
  }, [started, text])

  return (
    <p className="font-serif text-[22px] sm:text-[26px] leading-[1.7] text-neutral-800 text-left text-pretty min-h-[1.7em]">
      {displayedText}
      {started && displayedText.length < text.length && (
        <span className="inline-block w-1 h-[1em] bg-neutral-400 ml-1 animate-pulse align-middle" />
      )}
    </p>
  )
}
